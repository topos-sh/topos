#!/usr/bin/env node
/**
 * gen-plane-types.mjs — mirror the two facts this app serves but does NOT author: the SESSION
 * WIRE's types, and the release version of the build serving it.
 *
 *   ../contracts/openapi/openapi.json  →  app/lib/plane/contract/schema.d.ts
 *   ../contracts/schemas/json-envelope.schema.json → the same file's wire version
 *   ../Cargo.toml                      →  app/lib/plane/contract/version.ts (the release version)
 *
 * Since the identity unification the committed OpenAPI describes the `/v1` session lane the
 * PRODUCT APP itself serves (the vault has no public routes) — the Rust repo produces it from
 * the shared wire DTOs, and this generator keeps a typed mirror in the web tree. The gate's
 * value is LOCKSTEP: when the contract moves, `check:contract` fails until the types are
 * regenerated and the served routes are reconciled against the diff.
 *
 * The version is the same discipline applied to the repo's ONE version statement: the workspace
 * manifest's `[workspace.package] version` is what the release tag matches and what the CLI
 * compiles in, so the app declares THAT number on its protocol card rather than a second one
 * kept by hand — a bump that forgets this file fails the gate instead of shipping a lie.
 *
 * Usage:
 *   node scripts/gen-plane-types.mjs           regenerate the committed artifacts
 *   node scripts/gen-plane-types.mjs --check    regenerate to memory + byte-compare (drift gate)
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const WEB_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OPENAPI_PATH = resolve(WEB_ROOT, "..", "contracts", "openapi", "openapi.json");
const ENVELOPE_SCHEMA_PATH = resolve(
  WEB_ROOT,
  "..",
  "contracts",
  "schemas",
  "json-envelope.schema.json",
);
const CARGO_PATH = resolve(WEB_ROOT, "..", "Cargo.toml");
const TYPES_OUT = join(WEB_ROOT, "app", "lib", "plane", "contract", "schema.d.ts");
const VERSION_OUT = join(WEB_ROOT, "app", "lib", "plane", "contract", "version.ts");

/**
 * The served session wire, whole: every `/v1` route in the committed contract is this app's to
 * serve now, so the pruning list IS the contract's own path table (a route the contract adds
 * that this list misses fails the gate loudly, forcing the reconcile).
 */
const PUBLIC_ROUTES = [
  { method: "post", path: "/v1/login/authorize" },
  { method: "post", path: "/v1/login/connect" },
  { method: "post", path: "/v1/login/token" },
  { method: "delete", path: "/v1/session" },
  { method: "post", path: "/v1/proposals" },
  { method: "post", path: "/v1/publish" },
  { method: "post", path: "/v1/reverts" },
  { method: "post", path: "/v1/reviews" },
  { method: "get", path: "/v1/workspaces/{ws}/channels" },
  { method: "put", path: "/v1/workspaces/{ws}/channels/{ch}/protection" },
  { method: "get", path: "/v1/workspaces/{ws}/delivery" },
  { method: "post", path: "/v1/workspaces/{ws}/invitations" },
  { method: "get", path: "/v1/workspaces/{ws}/mcp-servers/{skill}/revisions/{revision_id}" },
  { method: "get", path: "/v1/workspaces/{ws}/me" },
  { method: "post", path: "/v1/workspaces/{ws}/notices/ack" },
  { method: "get", path: "/v1/workspaces/{ws}/proposals" },
  { method: "put", path: "/v1/workspaces/{ws}/report" },
  { method: "get", path: "/v1/workspaces/{ws}/skills" },
  { method: "get", path: "/v1/workspaces/{ws}/skills/{skill}/bundles/{object_id}" },
  { method: "get", path: "/v1/workspaces/{ws}/skills/{skill}/current" },
  { method: "get", path: "/v1/workspaces/{ws}/skills/{skill}/log" },
  { method: "get", path: "/v1/workspaces/{ws}/skills/{skill}/proposals" },
  { method: "put", path: "/v1/workspaces/{ws}/skills/{skill}/protection" },
  { method: "get", path: "/v1/workspaces/{ws}/skills/{skill}/versions/{version_id}" },
];

const GENERATED_HEADER = `/**
 * Generated by scripts/gen-plane-types.mjs from ../contracts/openapi/openapi.json — do not edit.
 * Regenerate with: bun run gen:plane
 *
 * NOTHING IMPORTS THIS FILE. It exists solely as the byte-comparison target of the
 * \`check:contract\` drift gate, which re-renders it from the committed contract and fails when
 * the two differ — so the contract cannot move without the reconcile being noticed. The live
 * \`@/lib/plane/contract/…\` imports all target \`contract/version\` instead.
 */
`;

/** Prune to the served routes (today: the whole table); keep components whole. */
function buildPublicDocument(document) {
  const paths = {};
  for (const { method, path } of PUBLIC_ROUTES) {
    const operation = document.paths?.[path]?.[method];
    if (!operation) {
      throw new Error(
        `served route missing from the committed contract: ${method.toUpperCase()} ${path}`,
      );
    }
    // Merge methods into the SAME path object — a path can carry more than one verb, and a
    // per-entry overwrite would drop all but the last.
    paths[path] = { ...(paths[path] ?? {}), [method]: operation };
  }
  return {
    openapi: document.openapi,
    info: {
      title: "topos session wire — the served /v1 lane",
      description:
        "The /v1 session lane the product app serves. Generated by " +
        "scripts/gen-plane-types.mjs — do not edit.",
      version: document.info?.version ?? "0.0.0",
    },
    paths,
    components: document.components,
  };
}

async function render() {
  const { default: openapiTS, astToString } = await import("openapi-typescript");
  const document = JSON.parse(readFileSync(OPENAPI_PATH, "utf8"));
  const ast = await openapiTS(buildPublicDocument(document));
  return GENERATED_HEADER + astToString(ast);
}

/**
 * The workspace's release version, read from `[workspace.package]` ALONE. The section is walked
 * to explicitly: a manifest is full of `version = "…"` lines, and every one of them outside that
 * table belongs to a dependency — reading the first match would put some crate's pin on the
 * protocol card.
 */
function workspaceVersion() {
  let section = "";
  for (const line of readFileSync(CARGO_PATH, "utf8").split("\n")) {
    const header = line.match(/^\s*\[([^\]]+)]/);
    if (header !== null) {
      section = header[1];
      continue;
    }
    const hit = section === "workspace.package" && line.match(/^\s*version\s*=\s*"([^"]+)"/);
    if (hit) {
      return hit[1];
    }
  }
  throw new Error(`no [workspace.package] version in ${CARGO_PATH}`);
}

/**
 * The WIRE contract's own version, read off the envelope schema's pinned `const` — the number
 * every document this tier emits carries. It is the Rust `WIRE_SCHEMA_VERSION` by construction
 * (the schema is generated from it), so the two tiers cannot stamp different versions on one
 * contract. Read from the JSON-Schema rather than the OpenAPI: only the former pins the value.
 */
function wireSchemaVersion() {
  const schema = JSON.parse(readFileSync(ENVELOPE_SCHEMA_PATH, "utf8"));
  const pinned = schema.properties?.schema_version?.const;
  if (typeof pinned !== "number") {
    throw new Error(`no pinned schema_version in ${ENVELOPE_SCHEMA_PATH}`);
  }
  return pinned;
}

function renderVersion() {
  return (
    `/**\n` +
    ` * Generated by scripts/gen-plane-types.mjs from ../Cargo.toml + ../contracts/openapi/openapi.json\n` +
    ` * — do not edit. Regenerate with: bun run gen:plane\n` +
    ` */\n` +
    `\n` +
    `/** The release version of the build serving this app — what the protocol card declares. */\n` +
    `export const SERVER_RELEASE_VERSION = "${workspaceVersion()}";\n` +
    `\n` +
    `/** The wire contract's version — stamped on every document this tier emits. */\n` +
    `export const WIRE_SCHEMA_VERSION = ${wireSchemaVersion()};\n` +
    `\n` +
    `/**\n` +
    ` * The versions this tier still READS on the way in. A deployed client speaks the version it\n` +
    ` * was built with, and the min-CLI floor admits releases older than this contract — so the\n` +
    ` * door accepts those too, or a deploy would refuse every machine in the field.\n` +
    ` */\n` +
    `export const ACCEPTED_WIRE_SCHEMA_VERSIONS: readonly number[] = [${[
      ...new Set([wireSchemaVersion(), 1]),
    ]
      .sort((a, b) => a - b)
      .join(", ")}];\n`
  );
}

const check = process.argv.includes("--check");
const artifacts = [
  { out: TYPES_OUT, text: await render() },
  { out: VERSION_OUT, text: renderVersion() },
];

for (const { out, text } of artifacts) {
  const rel = out.slice(WEB_ROOT.length + 1);
  if (check) {
    let current;
    try {
      current = readFileSync(out, "utf8");
    } catch {
      console.error(`contract drift: ${rel} is missing — run \`bun run gen:plane\``);
      process.exit(1);
    }
    if (current !== text) {
      console.error(`contract drift: ${rel} is stale — run \`bun run gen:plane\``);
      process.exit(1);
    }
    console.warn(`contract types in sync (${rel})`);
  } else {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, text);
    console.warn(`wrote ${rel}`);
  }
}
