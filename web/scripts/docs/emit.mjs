/**
 * Serialize a compiled content set into the module the app imports.
 *
 * Deterministic by construction: pages follow nav order, every object is written with a fixed
 * key order, and nothing carries a timestamp, a hostname, or an absolute path. That is what
 * makes `gen:docs --check` a drift gate rather than a coin flip — the file changes when, and
 * only when, the documentation changes.
 */

const HEADER = `// GENERATED by \`bun run gen:docs\` from the repo's docs/ — DO NOT EDIT.
// Edit the MDX under docs/, re-run \`bun run gen:docs\`, and commit the result.
// \`bun run check\` fails when this file and docs/ disagree.
`;

/** JSON is a subset of TS object syntax; a fixed key order keeps the output byte-stable. */
function literal(value) {
  return JSON.stringify(value, null, 2);
}

export function emitModule({ nav, order, pages }) {
  const records = {};
  for (const page of pages) {
    records[page.id] = {
      id: page.id,
      title: page.title,
      description: page.description,
      sidebarLabel: page.sidebarLabel,
      html: page.html,
      markdown: page.markdown,
      headings: page.headings.map((heading) => ({
        depth: heading.depth,
        id: heading.id,
        text: heading.text,
      })),
    };
  }
  return [
    HEADER,
    'import type { DocsNavGroup, DocsPage } from "./model";',
    "",
    "/** The sidebar, straight from docs/nav.json. */",
    `export const DOCS_NAV: readonly DocsNavGroup[] = ${literal(nav)};`,
    "",
    "/** Every page id in reading order — the order prev/next walks. */",
    `export const DOCS_ORDER: readonly string[] = ${literal(order)};`,
    "",
    "/** Every compiled page, keyed by id. */",
    `export const DOCS_PAGES: Readonly<Record<string, DocsPage>> = ${literal(records)};`,
    "",
  ].join("\n");
}
