#!/usr/bin/env node
/**
 * gen-mcp-secret-patterns.mjs — compile the shared credential-shape vectors into the committed
 * module the MCP validator reads.
 *
 *   bun run gen:mcp-patterns            write app/lib/mcp/secret-patterns.generated.ts
 *   bun run gen:mcp-patterns --check    regenerate in memory and fail on drift (the CI gate)
 *
 * The SOURCE is `tests/fixtures/mcp/secret-patterns.json` at the REPO root — the one file both
 * languages read, so the client and this tier can never disagree about what a credential looks
 * like. It is generated rather than read at runtime for the same reason the documentation is:
 * the deployed image ships `web/` alone, and a server that reads its rules off disk fails
 * differently depending on how it was packaged. Edit the JSON → regenerate → commit; the drift
 * gate keeps the two honest and a vitest re-compares them value for value.
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const WEB_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const REPO_ROOT = resolve(WEB_ROOT, "..");
const SOURCE = join(REPO_ROOT, "tests", "fixtures", "mcp", "secret-patterns.json");
const GENERATED = join(WEB_ROOT, "app", "lib", "mcp", "secret-patterns.generated.ts");

const check = process.argv.includes("--check");
const target = relative(WEB_ROOT, GENERATED);

/** Fail loudly on a malformed source rather than emitting a module that silently scans nothing. */
function validate(parsed) {
  if (!Array.isArray(parsed.patterns) || parsed.patterns.length === 0) {
    throw new Error("secret-patterns.json: `patterns` must be a non-empty array");
  }
  for (const entry of parsed.patterns) {
    if (typeof entry?.name !== "string" || typeof entry?.regex !== "string") {
      throw new Error("secret-patterns.json: every pattern needs a string `name` and `regex`");
    }
    // Compile it here so a broken regex fails the GENERATE, never a request.
    new RegExp(entry.regex);
  }
  const entropy = parsed.entropy;
  if (
    typeof entropy?.minLength !== "number" ||
    typeof entropy?.threshold !== "number" ||
    entropy.minLength < 1 ||
    entropy.threshold <= 0
  ) {
    throw new Error("secret-patterns.json: `entropy` needs positive minLength and threshold");
  }
}

function emit(parsed) {
  const patterns = parsed.patterns
    .map((p) => `  { name: ${JSON.stringify(p.name)}, regex: ${JSON.stringify(p.regex)} },`)
    .join("\n");
  return `// GENERATED by scripts/gen-mcp-secret-patterns.mjs — DO NOT EDIT.
// Source: tests/fixtures/mcp/secret-patterns.json (the repo-root vectors both languages read).
// Run \`bun run gen:mcp-patterns\` after editing the source; \`bun run check\` fails on drift.

/** One named credential shape, as ECMAScript regex SOURCE (unanchored, case-sensitive). */
export interface SecretPattern {
  name: string;
  regex: string;
}

export const SECRET_PATTERNS: readonly SecretPattern[] = [
${patterns}
];

/** The heuristic belt below the named shapes — see app/lib/mcp/validate.server.ts. */
export const SECRET_ENTROPY = {
  minLength: ${parsed.entropy.minLength},
  threshold: ${parsed.entropy.threshold},
} as const;
`;
}

async function main() {
  const parsed = JSON.parse(await readFile(SOURCE, "utf8"));
  validate(parsed);
  const next = emit(parsed);

  if (!check) {
    await writeFile(GENERATED, next);
    console.warn(
      `${target}: ${parsed.patterns.length} patterns from ${relative(WEB_ROOT, SOURCE)}`,
    );
    return;
  }

  const current = await readFile(GENERATED, "utf8").catch(() => null);
  if (current !== next) {
    console.error(
      `mcp secret-pattern drift check FAILED: ${target} does not match ${SOURCE}.\n` +
        "Run `bun run gen:mcp-patterns` and commit the result.",
    );
    process.exit(1);
  }
  console.warn(`mcp secret patterns in sync (${parsed.patterns.length})`);
}

main().catch((error) => {
  console.error(`mcp secret patterns: ${error instanceof Error ? error.message : String(error)}`);
  process.exit(1);
});
